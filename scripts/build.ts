#!/usr/bin/env bun
import { builtinModules } from 'node:module'
import { join } from 'node:path'

// 플러그인이 띄우는 서버를 파일 하나로 묶는다: bun run build
// 쓰는 패키지를 모두 이 파일에 넣어서, 사용자 PC에서는 아무것도 깔지 않고 `bun --no-install` 로 바로 띄운다.
// 예전에는 처음 켤 때 bun install 을 했는데, 오래된 Bun 이 새 bun.lock 을 읽지 못해 Windows 에서 켜지지 않은 일이 있었다(2026-10-29).
// Claude 플러그인 디렉터리도 어떤 코드가 도는지 정확히 알 수 있게 이 방식을 요구한다(2026-11-09).
const root = join(import.meta.dir, '..')
const out = join(root, 'plugin', 'coworker.js')

const result = await Bun.build({
  entrypoints: [join(root, 'src', 'mcp.ts')],
  target: 'bun',
  outdir: join(root, 'plugin'),
  naming: 'coworker.js',
  banner: '// AI Co-worker Without Me: built from src/ by `bun run build`. Do not edit this file; change src/ and build again.',
})
if (!result.success) {
  for (const log of result.logs) console.error(log)
  process.exit(1)
}

// 묶은 파일이 바깥 패키지를 찾으면 사용자 PC에서 깔게 된다. 그런 import 가 남았으면 실패시킨다.
// 실제로 불러오는 자리(import … from, import(), 번들러의 __require)만 본다.
// ajv 는 코드를 만들 때 쓰는 문자열 안에 require("ajv/…") 를 담고 있는데, 그건 실행되지 않는다.
const text = await Bun.file(out).text()
const builtins = new Set(builtinModules)
const specifiers = [...text.matchAll(/(?:\bfrom\s*|\bimport\s*\(\s*|\b__require\s*\(\s*)["']([^"']+)["']/g)].map(m => m[1]!)
const outside = [...new Set(specifiers)].filter(s => !s.startsWith('node:') && !s.startsWith('bun:') && s !== 'bun' && !builtins.has(s))
if (outside.length) {
  console.error(`plugin/coworker.js still imports packages from outside the bundle: ${outside.join(', ')}`)
  process.exit(1)
}
console.log(`built plugin/coworker.js (${Math.round(text.length / 1024)} KiB)`)
